func TestSessionModel_SessionsLoaded(t *testing.T) {
	model := NewSessionModel()
	
	sampleItems := []list.Item{
		sessionItem{SessionInfo: session.SessionInfo{UUID: "uuid1", MessageCount: 5, IsLatest: true, LastModified: time.Now()}},
		sessionItem{SessionInfo: session.SessionInfo{UUID: "uuid2", MessageCount: 10, IsLatest: false, LastModified: time.Now().Add(-time.Hour)}},
	}
	
	updatedModel, _ := model.Update(sessionsLoadedMsg{items: sampleItems})
	model = updatedModel.(sessionModel)

	assert.False(t, model.isLoading, "isLoading should be false after sessions are loaded")
	assert.Equal(t, len(sampleItems), len(model.list.Items()), "List should be populated with loaded items")
	assert.Contains(t, model.statusMessage, fmt.Sprintf("%d sessions loaded", len(sampleItems)), "Status message mismatch")
}

func TestSessionModel_SelectAndSwitchSession(t *testing.T) {
	setupSessionMocks()
	defer teardownSessionMocks()

	model := NewSessionModel()

	// 1. Load sessions
	sampleSessionItems := []list.Item{
		sessionItem{SessionInfo: session.SessionInfo{UUID: "test-uuid-1", MessageCount: 2, IsLatest: false, LastModified: time.Now()}},
		sessionItem{SessionInfo: session.SessionInfo{UUID: "test-uuid-2", MessageCount: 3, IsLatest: true, LastModified: time.Now()}},
	}
	updatedModel, _ := model.Update(sessionsLoadedMsg{items: sampleSessionItems})
	model = updatedModel.(sessionModel)
	
	// 2. Select the first item (index 0)
	model.list.Select(0) // This directly manipulates the list's internal state.

	// 3. Simulate pressing Enter
	updatedModel, cmdEnter := model.Update(tea.KeyMsg{Type: tea.KeyEnter})
	model = updatedModel.(sessionModel)

	assert.True(t, model.isLoading, "isLoading should be true during switch operation")
	assert.NotNil(t, cmdEnter, "Enter key should return a command for switching and spinner")
	assert.Contains(t, model.statusMessage, "Switching to test-uuid-1...", "Status message for switching is incorrect")


	// 4. Simulate the switchedSessionMsg that would be generated by the command
	//    This bypasses testing the command execution directly, which is complex for tea.Cmd funcs.
	updatedModel, cmdSwitch := model.Update(switchedSessionMsg{uuid: "test-uuid-1"})
	model = updatedModel.(sessionModel)
	
	assert.Contains(t, model.statusMessage, "Switched to session test-uuid-1.", "Status message after switching is incorrect")
	assert.Equal(t, tea.Quit, cmdSwitch, "Update after switchedSessionMsg should return tea.Quit")

}


func TestSessionModel_QuitMessages(t *testing.T) {
	model := NewSessionModel()

	// Test Ctrl+C
	updatedModel, cmdCtrlC := model.Update(tea.KeyMsg{Type: tea.KeyCtrlC})
	model = updatedModel.(sessionModel)
	assert.Equal(t, tea.Quit, cmdCtrlC, "Ctrl+C should return tea.Quit command")
	assert.Contains(t, model.statusMessage, "Session selection cancelled.", "Status message for quit is incorrect")


	// Test Esc
	model = NewSessionModel() // Reset model state
	updatedModel, cmdEsc := model.Update(tea.KeyMsg{Type: tea.KeyEsc})
	model = updatedModel.(sessionModel)
	assert.Equal(t, tea.Quit, cmdEsc, "Esc should return tea.Quit command")
	assert.Contains(t, model.statusMessage, "Session selection cancelled.", "Status message for quit is incorrect")
}

