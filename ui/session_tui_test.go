func TestSessionModel_WindowResize(t *testing.T) {
	model := NewSessionModel()
	
	// Send an initial one to set it up and make model.ready true if that's a pattern
	model, _ = model.Update(tea.WindowSizeMsg{Width: 80, Height: 24})
	model = model.(sessionModel) // type assertion

	newWidth := 100
	newHeight := 30
	updatedModel, _ := model.Update(tea.WindowSizeMsg{Width: newWidth, Height: newHeight})
	model = updatedModel.(sessionModel)

	// Check if list dimensions are updated.
	// The list sets its size considering padding and other elements.
	// Exact calculation depends on appStyle, titleStyle, helpStyle heights.
	// For simplicity, just check that width has changed. A more robust test would calculate expected values.
	currentListWidth, _ := model.list.Size()
	assert.NotEqual(t, 80-appStyle.GetHorizontalPadding(), currentListWidth, "List width should have been updated by WindowSizeMsg")
	assert.Equal(t, newWidth-appStyle.GetHorizontalPadding(), currentListWidth, "List width not correctly set after resize")
}

